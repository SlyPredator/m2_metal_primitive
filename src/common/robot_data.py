import numpy as np
from common import utility as ram


class Robot:
    class Body:
        def __init__(self, parent, name, pos, quat, ipos, iquat,
                     mass, inertia, joint_axis, joint_range):
            self.parent = parent
            self.name = name
            self.pos = np.array(pos)
            self.quat = np.array(quat)
            self.ipos = np.array(ipos)
            self.iquat = np.array(iquat)
            self.mass = mass
            self.inertia = np.array(inertia)
            self.joint_axis = np.array(joint_axis)
            self.joint_range = np.array(joint_range)

    class Params:
        def __init__(self):
            self.end_eff_pos_local = np.array([-0.0035143, 0, -0.1901])
            self.q_base = np.array([0.0, 0.0, 0.32, 1.0, 0.0, 0.0, 0.0])
            self.foot_geom_names = ["FL_foot", "FR_foot", "RL_foot", "RR_foot"]
            self.q_leg_nominal = np.array([0.0, 0.7, -1.4])

    def __init__(self):
        self.body = {}
        self.params = Robot.Params()

    def add_body(self, bid, parent, name, pos, quat, ipos, iquat, mass, inertia, joint_axis, joint_range):
        self.body[bid] = Robot.Body(parent, name, pos, quat, ipos, iquat, mass, inertia, joint_axis, joint_range)

